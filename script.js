// Update modal price
function updateModalPrice() {
    if (!selectedVilla) return;
    
    const villa = villasData[selectedVilla];
    const checkin = document.getElementById('modalCheckin').value;
    const checkout = document.getElementById('modalCheckout').value;
    const totalPriceEl = document.getElementById('modalTotalPrice');
    
    if (!checkin || !checkout || !totalPriceEl) return;
    
    const checkinDate = new Date(checkin);
    const checkoutDate = new Date(checkout);
    const nights = Math.ceil((checkoutDate - checkinDate) / (1000 * 60 * 60 * 24));
    
    if (nights > 0) {
        const totalPrice = villa.price * nights;
        totalPriceEl.value = `${totalPrice.toFixed(2)}€ (${nights} nuit${nights > 1 ? 's' : ''})`;
    } else {
        totalPriceEl.value = `${villa.price.toFixed(2)}€/nuit`;
    }
}

