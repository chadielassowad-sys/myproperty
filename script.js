function initLanguageSelector() {
    const selector = document.getElementById('languageSelector');
    const btn = document.getElementById('langBtn');
    const dropdown = document.getElementById('langDropdown');
    
    if (!selector || !btn || !dropdown) return;

    // Set current language
    updateLanguageDisplay();

    // Toggle dropdown
    btn.addEventListener('click', function(e) {
        e.stopPropagation();
        selector.classList.toggle('active');
    });

    // Close on outside click
    document.addEventListener('click', function(e) {
        if (!selector.contains(e.target)) {
            selector.classList.remove('active');
        }
    });

    // Language selection
    const options = dropdown.querySelectorAll('.lang-option');
    options.forEach(option => {
        option.addEventListener('click', function() {
            const lang = this.dataset.lang;
            changeLanguage(lang);
            selector.classList.remove('active');
        });
    });

    // Mark active language
    updateActiveLanguage();
}

function updateLanguageDisplay() {
    const lang = languageData[currentLanguage];
    if (!lang) return;

    const codeEl = document.getElementById('currentLang');
    
    if (codeEl) codeEl.textContent = lang.code;
}

function updateActiveLanguage() {
    const options = document.querySelectorAll('.lang-option');
    options.forEach(option => {
        if (option.dataset.lang === currentLanguage) {
            option.classList.add('active');
        } else {
            option.classList.remove('active');
        }
    });
}

function changeLanguage(lang) {
    if (!languageData[lang] || lang === currentLanguage) return;
    
    currentLanguage = lang;
    localStorage.setItem('selectedLanguage', lang);
    
    updateLanguageDisplay();
    updateActiveLanguage();
    translatePage();
    
    showMessage(`${languageData[lang].name}`, 'success');
}

