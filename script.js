function changeVdImage(direction) {
    currentVdImageIndex += direction;
    if (currentVdImageIndex < 0) currentVdImageIndex = currentVdImages.length - 1;
    if (currentVdImageIndex >= currentVdImages.length) currentVdImageIndex = 0;
    updateVdHeroImage(true);
}

function openVdLightbox(index) {
    currentGalleryImages = currentVdImages;
    openLightbox(index);
}

// Click on card → open detail (ignore button clicks)
document.addEventListener('click', function(e) {
    const card = e.target.closest('.villa-card');
    if (!card) return;
    if (e.target.closest('.favorite-btn, .view-gallery-btn, .reserve-btn')) return;
    const villaId = card.dataset.villa;
    if (villaId) openVillaDetail(villaId);
});

// Keyboard: Escape closes detail modal, arrows navigate hero
document.addEventListener('keydown', function(e) {
    const detailModal = document.getElementById('villaDetailModal');
    if (detailModal && detailModal.classList.contains('open')) {
        if (e.key === 'Escape') closeVillaDetail();
        if (e.key === 'ArrowLeft') changeVdImage(-1);
        if (e.key === 'ArrowRight') changeVdImage(1);
    }
});

