function translateVillaCards() {
    const cards = document.querySelectorAll('.villa-card');
    cards.forEach(card => {
        const villaId = card.dataset.villa;
        if (!villaId || !villaTranslations[villaId]) return;

        const translation = villaTranslations[villaId][currentLanguage];
        if (!translation) return;

        const descEl = card.querySelector('.villa-description');
        if (descEl) descEl.textContent = translation;
    });
}
