// Initialize date inputs
function initializeDates() {
    const today = new Date();
    const tomorrow = new Date(today);
    tomorrow.setDate(tomorrow.getDate() + 1);
    const nextWeek = new Date(today);
    nextWeek.setDate(nextWeek.getDate() + 7);

    const checkin = document.getElementById('checkin');
    const checkout = document.getElementById('checkout');
    const modalCheckin = document.getElementById('modalCheckin');
    const modalCheckout = document.getElementById('modalCheckout');

    if (checkin) {
        checkin.min = today.toISOString().split('T')[0];
        checkin.value = today.toISOString().split('T')[0];
    }
    if (checkout) {
        checkout.min = tomorrow.toISOString().split('T')[0];
        checkout.value = nextWeek.toISOString().split('T')[0];
    }
    if (modalCheckin) {
        modalCheckin.min = today.toISOString().split('T')[0];
    }
    if (modalCheckout) {
        modalCheckout.min = tomorrow.toISOString().split('T')[0];
    }

    // Update checkout min when checkin changes
    if (checkin && checkout) {
        checkin.addEventListener('change', function() {
            const checkinDate = new Date(checkin.value);
            const minCheckout = new Date(checkinDate);
            minCheckout.setDate(minCheckout.getDate() + 1);
            checkout.min = minCheckout.toISOString().split('T')[0];
            if (new Date(checkout.value) <= checkinDate) {
                checkout.value = minCheckout.toISOString().split('T')[0];
            }
        });
    }

    if (modalCheckin && modalCheckout) {
        modalCheckin.addEventListener('change', function() {
            const checkinDate = new Date(modalCheckin.value);
            const minCheckout = new Date(checkinDate);
            minCheckout.setDate(minCheckout.getDate() + 1);
            modalCheckout.min = minCheckout.toISOString().split('T')[0];
            if (new Date(modalCheckout.value) <= checkinDate) {
                modalCheckout.value = minCheckout.toISOString().split('T')[0];
            }
            updateModalPrice();
        });

        modalCheckout.addEventListener('change', function() {
            updateModalPrice();
        });

        const modalGuests = document.getElementById('modalGuests');
        if (modalGuests) {
            modalGuests.addEventListener('change', updateModalPrice);
        }
    }
}

